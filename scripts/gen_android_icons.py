#!/usr/bin/env python3
"""Generate the Android launcher icons from the committed PNGs.

    python scripts/gen_android_icons.py

Writes into packaging/android/res/, which Cargo.toml points `resources` at and
`aapt2 compile --dir` reads whole. Run it after changing icon.svg (and after
re-running icon/generate-icons.bat, which is what turns the SVG into the PNGs
this reads -- nothing here rasterizes the SVG, because its mesh gradient needs
Inkscape).

Two sets come out, and both are wanted:

* `mipmap-<density>/ic_launcher.png` -- the legacy bitmap. Nothing with
  min_sdk 26 shows it on the home screen, but it is still what `@mipmap/
  ic_launcher` resolves to outside the launcher.
* `mipmap-anydpi-v26/ic_launcher.xml` plus `ic_launcher_foreground.png` -- the
  adaptive icon, which is what every device that can install this APK actually
  draws. Without it the launcher applies "legacy treatment": it shrinks the
  bitmap to about 0.7x and composites it onto a generated white rounded plate,
  so a full-bleed tile like ours comes out as a small double-rounded badge
  floating in a white blob. That is a perfectly good description of "there is
  no icon".

The adaptive foreground is drawn on the standard 108dp canvas with the artwork
at 72dp, which is exactly the window a launcher shows; the mask then rounds it
to whatever shape the device uses. The corners the artwork does not cover are
transparent, so the background colour shows through -- which is why the
background is the panel's own black rather than anything else.
"""

import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "packaging", "android", "res")

# Density buckets, as a multiple of mdpi.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}

#: Legacy launcher bitmap, in dp.
LEGACY_DP = 48
#: Adaptive icon canvas, in dp. Fixed by the platform.
ADAPTIVE_DP = 108
#: How much of that canvas a launcher actually shows, in dp. Also fixed.
VISIBLE_DP = 72

#: The panel colour from icon.svg, behind the artwork's rounded corners.
BACKGROUND = "#000000"

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_android_icons.py -- do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_android_icons.py -- do not edit by hand. -->
<resources>
    <color name="ic_launcher_background">{background}</color>
</resources>
"""


def source() -> Image.Image:
    """The largest committed PNG, so every output is a downscale."""
    return Image.open(os.path.join(ROOT, "icon", "icon1024.png")).convert("RGBA")


def write(path: str, image: Image.Image) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    image.save(path, "PNG", optimize=True)
    print(f"  {os.path.relpath(path, ROOT)}  {image.width}x{image.height}")


def main() -> None:
    art = source()

    print("legacy bitmaps:")
    for bucket, scale in DENSITIES.items():
        size = round(LEGACY_DP * scale)
        write(
            os.path.join(RES, f"mipmap-{bucket}", "ic_launcher.png"),
            art.resize((size, size), Image.LANCZOS),
        )

    print("adaptive foregrounds:")
    for bucket, scale in DENSITIES.items():
        canvas_px = round(ADAPTIVE_DP * scale)
        art_px = round(VISIBLE_DP * scale)
        layer = Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
        inset = (canvas_px - art_px) // 2
        layer.paste(art.resize((art_px, art_px), Image.LANCZOS), (inset, inset))
        write(os.path.join(RES, f"mipmap-{bucket}", "ic_launcher_foreground.png"), layer)

    print("descriptors:")
    for rel, text in (
        (os.path.join("mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE_XML),
        (os.path.join("values", "ic_launcher_background.xml"),
         BACKGROUND_XML.format(background=BACKGROUND)),
    ):
        path = os.path.join(RES, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"  {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
